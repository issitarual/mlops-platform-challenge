"""Builds (or reuses) the image for a project: same inputs -> same image (ADR-005)."""

import hashlib
import json
import re
import shutil
import tempfile
from pathlib import Path

from mlship.domain.environment import (
    EnvironmentInputs,
    LockState,
    PreparedEnvironment,
    ResolvedLock,
)
from mlship.domain.errors import (
    EnvironmentBuildError,
    EnvironmentMismatchError,
    LockResolutionError,
    MlshipError,
    ModelIntegrityError,
)
from mlship.domain.validation import Severity, ValidationIssue
from mlship.services.ports import (
    ContainerRuntime,
    DockerfileProvider,
    LockResolver,
    RuntimePackager,
)

LOCK_INPUTS_PREFIX = "# mlship-lock-inputs: "
LOCK_BODY_PREFIX = "# mlship-lock-body: "
LOCK_NOTICE = "# Generated by mlship from requirements.txt. Commit it; do not edit it by hand.\n"
_LABEL_PREFIX = "org.mlship."
_DECORATION = re.compile(r"^[^\w'\"(]+")
_NETWORK_FAILURE = re.compile(
    r"failed to fetch|error sending request|dns error|connection refused|timed out|"
    r"network is unreachable|tcp connect error",
    re.IGNORECASE,
)


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _render_lock(inputs_sha256: str, body: str) -> str:
    """Two header lines (what was resolved, hash of the rest), then notice and pins."""
    rest = LOCK_NOTICE + body
    return f"{LOCK_INPUTS_PREFIX}{inputs_sha256}\n{LOCK_BODY_PREFIX}{_sha256_text(rest)}\n{rest}"


def _check_lock(content: str, inputs_sha256: str) -> tuple[bool, bool]:
    """Return (inputs_match, body_intact) for an existing lock file."""
    first, _, after_first = content.partition("\n")
    second, _, rest = after_first.partition("\n")
    inputs_match = first == f"{LOCK_INPUTS_PREFIX}{inputs_sha256}"
    body_intact = second == f"{LOCK_BODY_PREFIX}{_sha256_text(rest)}"
    return inputs_match, body_intact


def _resolver_reason(details: str, limit: int = 600) -> str:
    """uv's explanation on one line, without its box-drawing decoration."""
    lines = (_DECORATION.sub("", line.strip()) for line in details.splitlines())
    reason = " ".join(line for line in lines if line)
    return reason if len(reason) <= limit else f"{reason[: limit - 3]}..."


def _write_atomically(path: Path, content: str) -> None:
    """Write via a temporary file + rename, so a crash never leaves half a lock."""
    temporary = path.with_name(f".{path.name}.tmp")
    try:
        temporary.write_text(content, encoding="utf-8", newline="\n")
        temporary.replace(path)  # atomic rename, also on Windows
    finally:
        temporary.unlink(missing_ok=True)


class EnvironmentService:
    def __init__(
        self,
        lock_resolver: LockResolver,
        runtime_packager: RuntimePackager,
        dockerfile: DockerfileProvider,
        container_runtime: ContainerRuntime,
        *,
        python_version: str,
        python_platform: str,
        docker_platform: str,
        lock_filename: str = "mlship.lock",
        image_repository: str = "mlship-env",
    ) -> None:
        self._lock_resolver = lock_resolver
        self._runtime = runtime_packager
        self._dockerfile = dockerfile
        self._containers = container_runtime
        self._python_version = python_version
        self._python_platform = python_platform
        self._docker_platform = docker_platform
        self._lock_filename = lock_filename
        self._image_repository = image_repository

    def lock(self, project_dir: Path) -> ResolvedLock:
        """Return an up-to-date lock, resolving only when its inputs changed.

        The lock lives next to ``requirements.txt`` so it can be committed and shared:
        re-running with the same inputs reuses it instead of picking newer versions.
        It is reused only if its body still matches the hash in its header; a lock
        that was edited, truncated or left with merge conflicts is resolved again.
        """
        requirements = project_dir / "requirements.txt"
        if not requirements.is_file():
            raise MlshipError(
                f"{requirements} not found.",
                hint="Create requirements.txt (it may be empty) or run `mlship init`.",
            )
        inputs_sha256 = self._lock_inputs_sha256(requirements)
        lock_path = project_dir / self._lock_filename

        discarded_modified = False
        if lock_path.is_file():
            current = lock_path.read_text(encoding="utf-8")
            inputs_match, body_intact = _check_lock(current, inputs_sha256)
            if inputs_match and body_intact:
                return ResolvedLock(lock_path, _sha256_text(current), inputs_sha256, reused=True)
            discarded_modified = inputs_match and not body_intact

        content = _render_lock(inputs_sha256, self._resolve(requirements))
        _write_atomically(lock_path, content)
        return ResolvedLock(
            lock_path,
            _sha256_text(content),
            inputs_sha256,
            reused=False,
            discarded_modified=discarded_modified,
        )

    def prepare(self, project_dir: Path) -> PreparedEnvironment:
        """Lock dependencies, then reuse the image for these inputs or build it."""
        return self._image_for(self.lock(project_dir))

    def lock_state(self, project_dir: Path) -> LockState:
        """Whether mlship.lock is what ``lock()`` would keep, without resolving anything."""
        lock_path = project_dir / self._lock_filename
        if not lock_path.is_file():
            return LockState.MISSING
        inputs = self._lock_inputs_sha256(project_dir / "requirements.txt")
        content = lock_path.read_text(encoding="utf-8", errors="replace")
        inputs_match, body_intact = _check_lock(content, inputs)
        if inputs_match and body_intact:
            return LockState.CURRENT
        return LockState.MODIFIED if inputs_match else LockState.STALE

    def check_resolution(self, project_dir: Path) -> ValidationIssue | None:
        """Can requirements.txt be resolved together with the runtime? (ADR-021)

        Read-only: the resolution goes to a temporary directory and the project is
        left untouched.
        """
        requirements = project_dir / "requirements.txt"
        try:
            self._resolve(requirements)
        except LockResolutionError as exc:
            if _NETWORK_FAILURE.search(exc.details):
                return ValidationIssue(
                    "REQUIREMENTS_INDEX_UNREACHABLE",
                    Severity.ERROR,
                    f"The package index could not be reached: {_resolver_reason(exc.details)}",
                    "requirements.txt",
                    "Check the network or the proxy, or run `mlship validate --offline` to "
                    "skip this check.",
                )
            return ValidationIssue(
                "REQUIREMENTS_UNRESOLVABLE",
                Severity.ERROR,
                f"{exc.message} {_resolver_reason(exc.details)}".strip(),
                "requirements.txt",
                exc.hint,
            )
        return None

    def _lock_inputs_sha256(self, requirements: Path) -> str:
        return _sha256_text(
            json.dumps(
                {
                    # read_text normalizes line endings: CRLF and LF give the same hash
                    "requirements_txt": _sha256_text(requirements.read_text(encoding="utf-8")),
                    "runtime": sorted(self._runtime.requirements()),
                    "python_version": self._python_version,
                    "python_platform": self._python_platform,
                },
                sort_keys=True,
            )
        )

    def _resolve(self, requirements: Path) -> str:
        """The resolved pins of requirements.txt plus the runtime, with hashes."""
        with tempfile.TemporaryDirectory(prefix="mlship-lock-") as tmp:
            work = Path(tmp)
            runtime_in = work / "mlship-runtime.in"
            runtime_in.write_text(
                "\n".join(sorted(self._runtime.requirements())) + "\n", encoding="utf-8"
            )
            shutil.copyfile(requirements, work / "requirements.txt")
            output = work / "lock.txt"
            self._lock_resolver.resolve([runtime_in, work / "requirements.txt"], output)
            return output.read_text(encoding="utf-8")

    def ensure_image_for_lock(
        self, lock_file: Path, expected_lock_sha256: str, expected_key: str
    ) -> PreparedEnvironment:
        """The environment of an earlier run, reused or rebuilt from its own lock (ADR-020).

        Both expected values come from the run's tags in the tracking database, not
        from the artifact store the lock was downloaded from. The lock must hash to
        what training recorded, and the recomputed key must equal the recorded key:
        a different key means the tool (runtime code, Dockerfile, base image) changed
        since, and serving would no longer use the environment the model was trained in.
        """
        content = lock_file.read_text(encoding="utf-8")
        lock_sha256 = _sha256_text(content)
        if lock_sha256 != expected_lock_sha256:
            raise ModelIntegrityError(
                "The lock file of this model's run does not match the hash recorded at "
                "training; its environment was not built.",
                hint="The artifact store was changed after training. Train the model "
                "again, and check who has write access to the artifact store.",
                details=f"recorded {expected_lock_sha256[:12]}…, downloaded {lock_sha256[:12]}…",
            )
        first = content.partition("\n")[0]
        lock = ResolvedLock(
            lock_file, lock_sha256, first.removeprefix(LOCK_INPUTS_PREFIX), reused=True
        )
        inputs = self._inputs(lock)
        if inputs.key() != expected_key:
            raise EnvironmentMismatchError(
                "The training environment of this model cannot be rebuilt identically.",
                hint="mlship changed since this model was trained (runtime, Dockerfile or "
                "base image). Train it again with this version of mlship, or serve it with "
                "the version that trained it.",
                details=f"expected environment key {expected_key[:16]}…, "
                f"rebuilt {inputs.key()[:16]}…",
            )
        return self._image_for(lock)

    def _inputs(self, lock: ResolvedLock) -> EnvironmentInputs:
        return EnvironmentInputs(
            lock_sha256=lock.sha256,
            runtime_source_sha256=self._runtime.source_sha256(),
            dockerfile_sha256=_sha256_text(self._dockerfile.render()),
            platform=self._docker_platform,
        )

    def _image_for(self, lock: ResolvedLock) -> PreparedEnvironment:
        dockerfile = self._dockerfile.render()
        inputs = self._inputs(lock)
        key = inputs.key()
        tag = f"{self._image_repository}:{key[:16]}"

        existing = self._containers.find_image(tag)
        if existing is not None:
            return PreparedEnvironment(existing, lock, inputs, cache_hit=True)

        labels = {
            f"{_LABEL_PREFIX}environment-key": key,
            f"{_LABEL_PREFIX}lock-sha256": inputs.lock_sha256,
            f"{_LABEL_PREFIX}runtime-source-sha256": inputs.runtime_source_sha256,
            f"{_LABEL_PREFIX}dockerfile-sha256": inputs.dockerfile_sha256,
        }
        with tempfile.TemporaryDirectory(prefix="mlship-build-") as tmp:
            context = Path(tmp)
            (context / "Dockerfile").write_text(dockerfile, encoding="utf-8", newline="\n")
            shutil.copyfile(lock.path, context / "requirements.lock")
            self._runtime.build_wheels(context / "wheels")
            image = self._containers.build_image(context, tag, labels)

        failure = self._containers.verify_image(tag)
        if failure is not None:
            self._containers.remove_image(tag)
            raise EnvironmentBuildError(
                "The environment image was built but failed its self-check; it was deleted.",
                hint="The usual cause is a full disk during the build. Free disk space "
                "(and, on Docker Desktop, run `docker builder prune`), then try again.",
                details=failure,
            )
        return PreparedEnvironment(image, lock, inputs, cache_hit=False)
