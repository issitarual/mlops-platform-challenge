"""FastAPI application factory.

``create_app`` verifies the model files and the load policy before anything else: an
instance that cannot prove it serves the registered model never starts.
"""

from fastapi import FastAPI

from mlship_runtime.serving.api import health, metrics
from mlship_runtime.serving.api.v1 import predict
from mlship_runtime.serving.core import errors
from mlship_runtime.serving.core.config import ServingSettings
from mlship_runtime.serving.core.lifespan import lifespan
from mlship_runtime.serving.core.middleware import BodySizeLimit, request_context
from mlship_runtime.serving.engines.model_engine import ModelEngine
from mlship_runtime.serving.schemas.predict import build_request_model


def create_app(settings: ServingSettings | None = None) -> FastAPI:
    settings = settings or ServingSettings()
    engine = ModelEngine(settings)
    engine.inspect()

    app = FastAPI(
        title=f"{settings.model_name} v{settings.model_version}",
        description="Model API generated by mlship. Health and metrics are outside /v1.",
        lifespan=lifespan,
    )
    app.state.settings = settings
    app.state.engine = engine
    app.state.ready = False
    errors.install(app)
    app.add_middleware(BodySizeLimit, max_bytes=settings.max_payload_bytes)
    app.middleware("http")(request_context)
    app.include_router(health.router)
    app.include_router(metrics.router)
    request_model = build_request_model(engine.columns, settings.max_batch_rows)
    app.include_router(predict.build_router(request_model, settings.request_timeout_seconds))
    return app
