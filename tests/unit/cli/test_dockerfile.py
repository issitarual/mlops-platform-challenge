from mlship.adapters.dockerfile import EnvironmentDockerfile


def test_rendered_dockerfile_enforces_the_install_policy() -> None:
    text = EnvironmentDockerfile("python:3.12-slim@sha256:" + "0" * 64).render()
    assert text.count("FROM python:3.12-slim@sha256:" + "0" * 64) == 2  # build + final stage
    assert "--require-hashes" in text
    assert "--only-binary=:all:" in text
    assert text.count("pip uninstall --yes pip") == 2  # build venv and final image
    assert "USER 10001:10001" in text
    assert "MLFLOW_DISABLE_AGENT_HINT=1" in text
    assert "MLFLOW_DISABLE_TELEMETRY=true" in text
    assert "$PATH" in text and "$$" not in text
    assert not any(
        line.endswith("\\\\") for line in text.splitlines()
    )  # continuation: one backslash


import pytest  # noqa: E402

from mlship.adapters.dockerfile import render_serving_dockerfile  # noqa: E402
from mlship.domain.environment import ImageRef  # noqa: E402
from mlship.domain.runs import ModelVersion  # noqa: E402
from mlship.domain.serving import ServingImageSpec  # noqa: E402


def _spec(name: str = "demo", trusted: tuple[str, ...] = ("a.B",)) -> ServingImageSpec:
    model = ModelVersion(name, 2, "run", "c" * 64)
    return ServingImageSpec(ImageRef("mlship-env:abc", "sha256:1"), model, False, trusted)


def test_serving_dockerfile_bakes_model_identity_and_load_policy() -> None:
    text = render_serving_dockerfile(_spec())
    assert text.startswith("# Generated by mlship")
    assert "FROM mlship-env:abc" in text
    assert "MLSHIP_SERVING_MODEL_SHA256=" + "c" * 64 in text
    assert "MLSHIP_SERVING_ALLOW_PICKLE=false" in text
    assert """MLSHIP_SERVING_SKOPS_TRUSTED_TYPES='["a.B"]'""" in text


@pytest.mark.parametrize(
    "spec", [_spec(name="x\nRUN curl evil"), _spec(trusted=("a'; RUN x",))], ids=["name", "types"]
)
def test_values_that_could_inject_dockerfile_instructions_are_refused(
    spec: ServingImageSpec,
) -> None:
    with pytest.raises(ValueError, match="unsafe"):
        render_serving_dockerfile(spec)
