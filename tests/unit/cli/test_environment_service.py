from pathlib import Path

import pytest
from fakes import FakeContainerRuntime, FakeDockerfile, FakeLockResolver, FakeRuntimePackager

from mlship.domain.errors import EnvironmentBuildError, MlshipError
from mlship.services.environment_service import LOCK_INPUTS_PREFIX, EnvironmentService


def _service(
    resolver: FakeLockResolver | None = None,
    packager: FakeRuntimePackager | None = None,
    dockerfile: FakeDockerfile | None = None,
    containers: FakeContainerRuntime | None = None,
) -> EnvironmentService:
    return EnvironmentService(
        resolver or FakeLockResolver(),
        packager or FakeRuntimePackager(),
        dockerfile or FakeDockerfile(),
        containers or FakeContainerRuntime(),
        python_version="3.12",
        python_platform="x86_64-manylinux_2_28",
        docker_platform="linux/amd64",
    )


@pytest.fixture
def project(tmp_path: Path) -> Path:
    (tmp_path / "requirements.txt").write_text("scikit-learn\n")
    return tmp_path


def test_lock_resolves_user_and_runtime_requirements_together(project: Path) -> None:
    resolver = FakeLockResolver()
    lock = _service(resolver=resolver).lock(project)
    assert not lock.reused
    assert resolver.calls == [["fastapi>=0.1\npydantic>=2\n", "scikit-learn\n"]]
    content = lock.path.read_text()
    assert content.startswith(LOCK_INPUTS_PREFIX + lock.inputs_sha256)
    assert "numpy==2.0.0" in content


def test_lock_is_reused_while_inputs_are_unchanged(project: Path) -> None:
    resolver = FakeLockResolver()
    service = _service(resolver=resolver)
    first = service.lock(project)
    second = service.lock(project)
    assert second.reused
    assert second.sha256 == first.sha256
    assert len(resolver.calls) == 1


def test_lock_is_resolved_again_when_requirements_change(project: Path) -> None:
    resolver = FakeLockResolver()
    service = _service(resolver=resolver)
    service.lock(project)
    (project / "requirements.txt").write_text("scikit-learn\npandas\n")
    assert not service.lock(project).reused
    assert len(resolver.calls) == 2


def test_line_endings_do_not_change_the_lock_inputs(project: Path) -> None:
    service = _service()
    lf = service.lock(project)
    (project / "requirements.txt").write_bytes(b"scikit-learn\r\n")
    crlf = service.lock(project)
    assert crlf.reused
    assert crlf.inputs_sha256 == lf.inputs_sha256


def test_lock_tells_humans_not_to_edit_it(project: Path) -> None:
    lines = _service().lock(project).path.read_text().splitlines()
    assert lines[2].startswith("# Generated by mlship")


@pytest.mark.parametrize(
    "corrupt",
    [
        pytest.param(lambda text: text[: len(text) // 2], id="truncated-write"),
        pytest.param(lambda text: text + "<<<<<<< HEAD\n", id="merge-conflict"),
        pytest.param(lambda text: text.replace("2.0.0", "1.0.0"), id="hand-edited-pin"),
    ],
)
def test_modified_lock_is_never_reused(project: Path, corrupt: object) -> None:
    resolver = FakeLockResolver()
    service = _service(resolver=resolver)
    original = service.lock(project)
    original.path.write_text(corrupt(original.path.read_text()))  # type: ignore[operator]

    again = service.lock(project)

    assert not again.reused
    assert again.discarded_modified
    assert again.sha256 == original.sha256  # regenerated from the same inputs
    assert len(resolver.calls) == 2


def test_lock_from_other_inputs_is_replaced_without_a_tamper_warning(project: Path) -> None:
    service = _service()
    service.lock(project)
    (project / "requirements.txt").write_text("pandas\n")
    assert not service.lock(project).discarded_modified


def test_lock_write_leaves_no_temporary_file(project: Path) -> None:
    _service().lock(project)
    assert sorted(p.name for p in project.iterdir()) == ["mlship.lock", "requirements.txt"]


def test_missing_requirements_file_is_a_clear_error(tmp_path: Path) -> None:
    with pytest.raises(MlshipError, match=r"requirements\.txt not found"):
        _service().lock(tmp_path)


def test_prepare_builds_once_then_hits_the_cache(project: Path) -> None:
    containers = FakeContainerRuntime()
    packager = FakeRuntimePackager()
    service = _service(packager=packager, containers=containers)

    first = service.prepare(project)
    second = service.prepare(project)

    assert not first.cache_hit
    assert second.cache_hit
    assert second.image == first.image
    assert len(containers.builds) == 1
    assert len(packager.built) == 1


def test_build_context_and_labels_carry_every_input(project: Path) -> None:
    containers = FakeContainerRuntime()
    prepared = _service(containers=containers).prepare(project)
    tag, labels, files = containers.builds[0]

    assert tag == f"mlship-env:{prepared.inputs.key()[:16]}"
    assert files == [
        "Dockerfile",
        "requirements.lock",
        "wheels",
        "wheels/mlship_runtime-0.1.0-py3-none-any.whl",
    ]
    assert labels["org.mlship.environment-key"] == prepared.inputs.key()
    assert labels["org.mlship.lock-sha256"] == prepared.lock.sha256


@pytest.mark.parametrize("change", ["runtime_source", "dockerfile"])
def test_changed_runtime_or_dockerfile_gives_a_new_image(project: Path, change: str) -> None:
    containers = FakeContainerRuntime()
    first = _service(containers=containers).prepare(project)
    packager = FakeRuntimePackager(source="t" * 64) if change == "runtime_source" else None
    dockerfile = FakeDockerfile("FROM other\n") if change == "dockerfile" else None
    second = _service(packager=packager, dockerfile=dockerfile, containers=containers).prepare(
        project
    )
    assert not second.cache_hit
    assert second.image.tag != first.image.tag


def test_new_image_is_verified_once_and_cached_image_is_not(project: Path) -> None:
    containers = FakeContainerRuntime()
    service = _service(containers=containers)
    first = service.prepare(project)
    service.prepare(project)
    assert containers.verified == [first.image.tag]


def test_image_failing_its_selfcheck_is_deleted_not_cached(project: Path) -> None:
    containers = FakeContainerRuntime(selfcheck_failure="typing_extensions.py (content differs)")
    service = _service(containers=containers)
    with pytest.raises(EnvironmentBuildError) as info:
        service.prepare(project)
    assert "disk" in info.value.hint
    assert "typing_extensions.py" in info.value.details
    assert containers.images == {}, "a broken image must not be reused by the next run"
